"""
範例五：神思機巧（PyTorch 深度學習與自動求導）
示範以純文言驅策 PyTorch 進行張量運算、自動求導與神經網絡訓練。
"""

import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent.parent))

from senran import 引入, 書, 疇

# 1. 引入 PyTorch 核心
神算 = 引入("torch")
神兵 = 引入("torch.nn")
調律 = 引入("torch.optim")

書("【森蚺】以文言驅策 PyTorch 深度神思：")

# 2. 張量運算與形貌
# 量 -> tensor, 皆零 -> zeros, 皆一 -> ones
甲 = 神算.量([[1.0, 2.0], [3.0, 4.0]])
乙 = 神算.皆一((2, 2))

書("甲張量形貌：", 甲.形)
書("甲乙兩陣相加：\n", 甲 + 乙)
書("甲乙矩陣乘積（矩積）：\n", 神算.矩積(甲, 乙))

# 3. 自動求導 (Autograd)
# 設權重 w = 2.0，求 f(w) = 3 * w^2 + 5 之梯度
# df/dw = 6 * w = 6 * 2.0 = 12.0
權 = 神算.量([2.0], requires_grad=True)
損 = 3 * (權 ** 2) + 5

書("\n--- 自動求導 (Autograd) ---")
書("當前權重：", 權.析值())
書("當前損耗：", 損.析值())

# 反溯 / 溯 -> backward()
損.反溯()
書("反溯所得之梯度（勢）：", 權.勢.析值()) # 勢 -> grad

# 4. 鍛造神經絡層 (Neural Network Training Loop)
書("\n--- 演練微型神經網絡（線性回歸擬合） ---")

# 目標規則：真理為 y = 2 * x + 3
訓練輸入 = 神算.量([[1.0], [2.0], [3.0], [4.0]])
真理目標 = 神算.量([[5.0], [7.0], [9.0], [11.0]])

# 建立單層線性模型 (Linear)
網絡 = 引入(神兵.Linear(1, 1))

# 建立精進器 (SGD Optimizer)
精進客 = 引入(調律.SGD(網絡.本.parameters(), lr=0.01))

# 歷練五十輪
for 輪 in 疇(1, 51):
    # 清空過往勢能 (zero_grad)
    精進客.清勢()
    
    # 前行推演 (forward)
    預測 = 網絡(訓練輸入)
    
    # 權衡損益 (MSE Loss)
    當前損 = ((預測 - 真理目標) ** 2).均()
    
    # 反向回溯求勢 (backward)
    當前損.反溯()
    
    # 步進更新權重 (step)
    精進客.步進()
    
    if 輪 % 10 == 0:
        書(f"第 {輪} 輪歷練，損耗之數：{當前損.析值():.4f}")

# 檢驗得道之成果：以 x = 5 測試（應當接近 13.0）
測試輸入 = 神算.量([[5.0]])
推測成果 = 網絡(測試輸入)
書(f"\n考驗新題 x=5，神思推測之果：{推測成果.析值():.2f}（真理為 13.00）")
書("善哉！神思大成！")
