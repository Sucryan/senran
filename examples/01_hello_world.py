"""
範例一：天地初開（基礎內建）
示範森蚺之基礎印出、數算、範圍迴圈與判定。
"""

import sys
from pathlib import Path
# 確保未安裝時亦可直接引用本地開發模組
sys.path.insert(0, str(Path(__file__).parent.parent))

from senran import 書, 計, 疇, 總, 錄, 譜, 序, 反, 若, 真, 假

# 1. 几案印出
書("【森蚺】問天地好在，四海安康！")

# 2. 數算與度量
名單 = 錄(["顏回", "子路", "子貢", "冉有"])
書("門徒人數：", 計(名單))

# 3. 劃定疆界 (range)
書("--- 報數三聲 ---")
for 數 in 疇(1, 4):
    書(f"第 {數} 聲：在！")

# 4. 排序與逆反
數列 = 錄([3, 1, 4, 1, 5, 9, 2, 6])
書("依理整飭：", 序(數列))
書("逆序而行：", 錄(反(數列)))

# 5. 若則邏輯
功名 = 100
若(功名 >= 60).則(
    lambda: 書("明斷：及格矣，善哉！")
).否則(
    lambda: 書("明斷：當焚膏繼晷，再接再厲。")
)
